    static final class Preset {
        final String name;
        final int width;
        final int height;
        final float[] conf;

        Preset(String name, int width, int height, float[] conf) {
            this.name = name;
            this.width = width;
            this.height = height;
            this.conf = conf;
        }
    }

    private Presets() {
    }

    private static float[] p(
            float cx, float cy, float x, float y,
            float ur, float vr, float up, float vp) {
        return new float[]{cx, cy, x, y, ur, vr, up, vp};
    }

    private static float[] p(float cx, float cy, float x, float y) {
        return p(cx, cy, x, y, 0, 0, 1, 1);
    }

    private static float[] conf(float[]... points) {
        float[] out = new float[points.length * 8];
        for (int i = 0; i < points.length; i++) {
            System.arraycopy(points[i], 0, out, i * 8, 8);
        }
        return out;
    }

